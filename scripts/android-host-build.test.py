    def test_outdated_source_fails_before_changing_existing_builder_or_native_state(self):
        source = self.root / 'pandaos'
        source.mkdir()
        host.run(['git', 'init', '--quiet', str(source)])
        self.write('pandaos/packages/app/src/index.ts', b'old source')
        builder = source / '.worktrees/android-build'
        self.write('pandaos/.worktrees/android-build/packages/app/src/index.ts', b'existing builder source')
        self.write('pandaos/.worktrees/android-build/packages/app/android/app/build/native.so', b'warm native cache')
        self.write('pandaos/.worktrees/android-build/.dev/android-host/sources.json', b'{"previous":"proof"}')
        self.write('pandaos/.worktrees/android-build/packages/app/.secrets/google-services.prod.json', b'preserved secret')
        args = Namespace(source=str(source), builder=str(builder), debug=False, requested_at=time.time())
        before = {str(path.relative_to(source)): path.read_bytes()
                  for path in source.rglob('*') if path.is_file()}
        for available in [None, 'scripts/prebuild-android.mjs', 'scripts/android-host-prebuilt.gradle']:
            with self.subTest(available=available):
                if available:
                    self.write('pandaos/' + available, b'one helper only')
                expected = dict(before)
                if available:
                    expected[available] = b'one helper only'
                with self.assertRaisesRegex(ValueError, 'Outdated Android build source, missing required tooling'):
                    host.build(args)
                actual = {str(path.relative_to(source)): path.read_bytes()
                          for path in source.rglob('*') if path.is_file()}
                self.assertEqual(actual, expected)
                if available:
                    (source / available).unlink()

