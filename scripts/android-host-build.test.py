    def test_artifact_reuse_requires_matching_sources_signer_and_actual_bytes(self):
        apk = self.write('app.apk', b'valid apk')
        receipt = {'sourceSHA256': 'source', 'signerSHA256': 'certificate', 'apkSHA256': host.digest(b'valid apk')}
        self.assertTrue(host.cache_hit(receipt, 'source', apk, 'certificate'))
        self.assertFalse(host.cache_hit(receipt, 'changed source', apk, 'certificate'))
