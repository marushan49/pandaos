        self.assertEqual(result, {'packages/app/src/index.ts': host.digest(b'new')})
        self.assertEqual(unchanged.read_bytes(), b'new')
        self.assertFalse((self.root / 'packages/app/src/removed.ts').exists())
        self.assertEqual(native.read_bytes(), b'native')
        self.assertEqual(modules.read_bytes(), b'cached dependency')

