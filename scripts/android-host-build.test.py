    def write(self, name, data):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return path

    def test_python_bytecode_does_not_change_source_or_artifact_cache(self):
        host.run(['git', 'init', '--quiet', str(self.root)])
        self.write('scripts/tool.py', b'print("source")\n')
        before = host.snapshot(self.root)
        apk = self.write('.dev/app.apk', b'verified apk')
        receipt = {'sourceSHA256': host.fingerprint(before), 'signerSHA256': 'certificate',
                   'apkSHA256': host.digest(apk.read_bytes())}
        self.write('scripts/__pycache__/tool.cpython-312.pyc', b'generated bytecode')
        self.write('scripts/tool.pyo', b'optimized bytecode')
        after = host.snapshot(self.root)
        self.assertEqual(after, before)
        self.assertTrue(host.cache_hit(receipt, host.fingerprint(after), apk, 'certificate'))

