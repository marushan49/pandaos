    def test_sync_updates_and_removes_owned_sources_without_touching_native_outputs(self):
        files = {'packages/app/src/index.ts': b'old', 'packages/app/src/removed.ts': b'remove'}
        initial = host.sync_sources(self.root, files, {})
        native = self.write('packages/app/android/app/build/native.so', b'native')
        modules = self.write('node_modules/react-native/build/native.so', b'cached dependency')
        unchanged = self.root / 'packages/app/src/index.ts'
        timestamp = unchanged.stat().st_mtime_ns
        self.assertEqual(host.sync_sources(self.root, files, initial), initial)
        self.assertEqual(unchanged.stat().st_mtime_ns, timestamp)
