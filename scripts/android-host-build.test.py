    def test_linked_workspace_exact_specs_normalize_but_ranges_registry_and_mismatches_do_not(self):
        sections = ['dependencies', 'devDependencies', 'peerDependencies', 'optionalDependencies']

        def inputs(version):
            root = {'name': 'root', 'version': version}
            client = {'name': '@getpaseo/client', 'version': version}
            for package in [root, client]:
                for section in sections:
                    package[section] = {'@getpaseo/client': version, 'external': '^7'}
            registry = {'version': '7', 'resolved': 'https://registry/native.tgz',
                        'integrity': 'sha512-external', 'dependencies': {'@getpaseo/client': version}}
            lock = {'version': version, 'packages': {'': root, 'packages/client': client,
                    'node_modules/@getpaseo/client': {'resolved': 'packages/client', 'link': True},
                    'node_modules/native': registry,
                    'packages/client/node_modules/nested': {'version': '3', 'integrity': 'nested'}}}
            return {'package.json': json.dumps(root).encode(),
                    'packages/client/package.json': json.dumps(client).encode(),
                    'package-lock.json': json.dumps(lock).encode()}

        files = inputs('1.0.0')
        baseline = host.fingerprint(host.dependency_inputs(files))
        bumped = inputs('2.0.0')
        lock = json.loads(bumped['package-lock.json'])
        lock['packages']['node_modules/native']['dependencies']['@getpaseo/client'] = '1.0.0'
        bumped['package-lock.json'] = json.dumps(lock).encode()
        self.assertEqual(host.fingerprint(host.dependency_inputs(bumped)), baseline)
        for path, field, value in [
                ('node_modules/native', 'resolved', 'https://registry/other.tgz'),
                ('node_modules/native', 'integrity', 'sha512-changed'),
                ('packages/client/node_modules/nested', 'version', '4')]:
            with self.subTest(path=path, field=field):
                changed = dict(bumped)
                changed_lock = json.loads(changed['package-lock.json'])
                changed_lock['packages'][path][field] = value
                changed['package-lock.json'] = json.dumps(changed_lock).encode()
                self.assertNotEqual(host.fingerprint(host.dependency_inputs(changed)), baseline)
        for path in ['package.json', 'packages/client/package.json']:
            for section in sections:
                for spec in ['^2.0.0', '1.0.0', '*']:
                    with self.subTest(path=path, section=section, spec=spec):
                        changed = dict(bumped)
                        package = json.loads(changed[path])
                        package[section]['@getpaseo/client'] = spec
                        changed[path] = json.dumps(package).encode()
                        self.assertNotEqual(host.fingerprint(host.dependency_inputs(changed)), baseline)
        for local_path in ['', 'packages/client']:
            changed = dict(bumped)
            changed_lock = json.loads(changed['package-lock.json'])
            changed_lock['packages'][local_path]['dependencies']['@getpaseo/client'] = '^2.0.0'
            changed['package-lock.json'] = json.dumps(changed_lock).encode()
            self.assertNotEqual(host.fingerprint(host.dependency_inputs(changed)), baseline)
        changed = dict(bumped)
        package = json.loads(changed['packages/client/package.json'])
        package['version'] = '3.0.0'
        changed['packages/client/package.json'] = json.dumps(package).encode()
        self.assertNotEqual(host.fingerprint(host.dependency_inputs(changed)), baseline)
        changed = dict(bumped)
        changed_lock = json.loads(changed['package-lock.json'])
        changed_lock['packages']['node_modules/@getpaseo/client']['link'] = False
        changed['package-lock.json'] = json.dumps(changed_lock).encode()
        self.assertNotEqual(host.fingerprint(host.dependency_inputs(changed)), baseline)

